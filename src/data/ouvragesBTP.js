export const LOTS_OUVRAGES = [...new Set(OUVRAGES_BTP.map((o) => o.lot))];
export const normaliserRecherche = (s) =>
  String(s || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
export function rechercherOuvrages(query = "", lot = "", custom = []) {
  const words = normaliserRecherche(query).split(/\s+/).filter(Boolean);
  return [...OUVRAGES_BTP, ...custom].filter(
    (o) =>
      (!lot || o.lot === lot) &&
      words.every((w) =>
        normaliserRecherche(o.designation + " " + o.lot).includes(w),
      ),
  );
}
